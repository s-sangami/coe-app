-- =====================================================================
-- OPTIONAL: exam_schedule (NOT deployed in production)
-- =====================================================================
-- This table DOES NOT EXIST in the production database (checked with
-- to_regclass('public.exam_schedule') = null). It is kept here only because
-- coe-app queries it in three places (see README, "Known gaps"). Without it
-- the app still works: the subject-name auto-fill and exam-date column for
-- QP Setting are empty, and "Upload Schedule" shows an error toast.
--
-- Run this file ONLY if you want that feature. It needs db/schema.sql
-- (exam_seasons) first. Nothing else in db/ depends on it.
-- Columns are all GUESSES inferred from the code: the code reads/writes
-- season_id, subject_code, subject_name, exam_date, session.
-- =====================================================================

create table if not exists public.exam_schedule (
  id           bigint generated by default as identity primary key,  -- GUESS: never referenced in code
  season_id    text not null
               references public.exam_seasons(id) on delete cascade,  -- GUESS: FK; cascade per owner decision
  subject_code text not null,                  -- upper-cased by the importer
  subject_name text,
  exam_date    date,                           -- GUESS: date; importer writes 'YYYY-MM-DD' or null
  session      text not null default ''        -- 'FN' / 'AN' or ''
);
create index if not exists exam_schedule_season_idx on public.exam_schedule (season_id);

-- Access: admins only. anon (the portal) never touches this table.
revoke all on public.exam_schedule from anon;
grant select, insert, update, delete on public.exam_schedule to authenticated;
alter table public.exam_schedule enable row level security;

drop policy if exists admin_all on public.exam_schedule;
create policy admin_all on public.exam_schedule
  for all to authenticated using (true) with check (true);
